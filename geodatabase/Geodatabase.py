class Geodatabase:
    """QGIS Plugin Implementation."""

    def __init__(self, iface):
        """Constructor.

        :param iface: An interface instance that will be passed to this class
            which provides the hook by which you can manipulate the QGIS
            application at run time.
        :type iface: QgsInterface
        """
        # Save reference to the QGIS interface
        self.iface = iface
        # initialize plugin directory
        self.plugin_dir = os.path.dirname(__file__)
        # initialize locale
        locale = QgsSettings().value('locale/userLocale', QLocale().name())[0:2]
        locale_path = os.path.join(
            self.plugin_dir,
            'i18n',
            '{}.qm'.format(locale))

        if os.path.exists(locale_path):
            self.translator = QTranslator()
            self.translator.load(locale_path)
            QCoreApplication.installTranslator(self.translator)

        # Declare instance attributes
        self.actions = []
        self.menu = self.tr(u'&Geodatabase')

        with open(os.path.join(self.plugin_dir,"src", "data", "service_url.json"), encoding="utf-8") as f:
            state_list = json.load(f)
        
        self.states = sorted(state_list.keys())  # Sort the state list alphabetically
        self.pluginIsActive = False

        # Check if plugin was started the first time in current QGIS session
        # Must be set in initGui() to survive plugin reloads
        self.first_start = None

    # noinspection PyMethodMayBeStatic
    def tr(self, message):
        """Get the translation for a string using Qt translation API.

        We implement this ourselves since we do not inherit QObject.

        :param message: String for translation.
        :type message: str, QString

        :returns: Translated version of message.
        :rtype: QString
        """
        # noinspection PyTypeChecker,PyArgumentList,PyCallByClass
        return QCoreApplication.translate('Geodatabase', message)


    def add_action(
        self,
        icon_path,
        text,
        callback,
        enabled_flag=True,
        add_to_menu=True,
        add_to_toolbar=True,
        status_tip=None,
        whats_this=None,
        parent=None):
        """Add a toolbar icon to the toolbar.

        :param icon_path: Path to the icon for this action. Can be a resource
            path (e.g. ':/plugins/foo/bar.png') or a normal file system path.
        :type icon_path: str

        :param text: Text that should be shown in menu items for this action.
        :type text: str

        :param callback: Function to be called when the action is triggered.
        :type callback: function

        :param enabled_flag: A flag indicating if the action should be enabled
            by default. Defaults to True.
        :type enabled_flag: bool

        :param add_to_menu: Flag indicating whether the action should also
            be added to the menu. Defaults to True.
        :type add_to_menu: bool

        :param add_to_toolbar: Flag indicating whether the action should also
            be added to the toolbar. Defaults to True.
        :type add_to_toolbar: bool

        :param status_tip: Optional text to show in a popup when mouse pointer
            hovers over the action.
        :type status_tip: str

        :param parent: Parent widget for the new action. Defaults None.
        :type parent: QWidget

        :param whats_this: Optional text to show in the status bar when the
            mouse pointer hovers over the action.

        :returns: The action that was created. Note that the action is also
            added to self.actions list.
        :rtype: QAction
        """

        icon = QIcon(icon_path)
        action = QAction(icon, text, parent)
        action.triggered.connect(callback)
        action.setEnabled(enabled_flag)

        if status_tip is not None:
            action.setStatusTip(status_tip)

        if whats_this is not None:
            action.setWhatsThis(whats_this)

        if add_to_toolbar:
            # Adds plugin icon to Plugins toolbar
            self.iface.addToolBarIcon(action)

        if add_to_menu:
            self.iface.addPluginToMenu(
                self.menu,
                action)

        self.actions.append(action)

        return action

    def initGui(self):
        """Create the menu entries and toolbar icons inside the QGIS GUI."""

        icon_path = os.path.join(os.path.dirname(__file__), 'icon.png')
        self.add_action(
            icon_path,
            text=self.tr(u'Load Geodata'),
            callback=self.run,
            parent=self.iface.mainWindow())
        # will be set False in run()
        self.first_start = True

    def create_quick_search_ui(self):
        self.state_combo_box = QComboBox()
        self.state_combo_box.addItems(self.states)
        self.state_combo_box.setMinimumWidth(50)

        self.quick_search_box = QLineEdit()
        self.quick_search_box.setPlaceholderText("Suchen notwendige Daten")
        self.quick_search_box.setMinimumWidth(50)

        self.my_toolbar = self.iface.addToolBar('Geodatabase')
        self.my_toolbar.setObjectName('GeodatabaseSearchToolbar')

        self.combo_action = self.my_toolbar.addWidget(self.state_combo_box)
        self.quick_search_action = self.my_toolbar.addWidget(self.quick_search_box)

        self.quick_search_box.returnPressed.connect(self.run_quick_search)
    
    def run_quick_search(self):
        keyword = self.quick_search_box.text().strip()
        selected_state = self.state_combo_box.currentText()
        if not keyword:
            return

        if not self.pluginIsActive:
            self.pluginIsActive = True
            if hasattr(self, 'reset_ui'):
                self.reset_ui()
            self.dlg.show()

        self.dlg.comboBox.setCurrentText(selected_state)
        self.dlg.lineEdit.setText(keyword)

        if hasattr(self, 'findServices'):
            self.findServices()

        self.quick_search_box.clear()
    
    def unload(self):
        """Removes the plugin menu item and icon from QGIS GUI."""
        if hasattr(self, 'my_toolbar'):
            self.iface.mainWindow().removeToolBar(self.my_toolbar)
            del self.combo_action        
            del self.quick_search_action
            del self.my_toolbar

        for action in self.actions:
            self.iface.removePluginMenu(
                self.tr(u'&Geodatabase'),
                action)
            self.iface.removeToolBarIcon(action)

    def findServices(self):
        if hasattr(self, 'worker') and self.worker is not None:
            if self.worker.isRunning():
                print("Worker is already running. Please wait for it to finish.")
                return

        
        city_name = self.dlg.comboBox.currentText()
        keyword = self.dlg.lineEdit.text().strip()
        self.dlg.pushButton.setEnabled(False)  # Disable the button to prevent multiple clicks

        self.worker = SearchWorker(city_name, keyword)
        self.worker.progress_update.connect(self.on_update_progress)
        self.worker.finished.connect(self.on_search_finished)
        self.worker.start()

    def on_update_progress(self, percentage):
        self.dlg.progressBar.setValue(percentage)

    def on_search_finished(self, results):
        self.dlg.pushButton.setEnabled(True)  # Re-enable the button
        if results:
            self.dlg.label_5.hide()  # Hide the "No results found" label
            self.dlg.tableWidget.show()  # Show the table view when there are results
            self.dlg.label_3.show()  # Show the label when there are results
            self.dlg.pushButton_2.show()  # Show the "Load Selected Layers" button when there are results
            self.dlg.tableWidget.setRowCount(len(results))
            for row, data in enumerate(results):
                title = data["title"]
                protocol = data["protocol"]
                url = data["url"]
                typename = data["typename"]
                self.dlg.tableWidget.setItem(row, 0, QTableWidgetItem(title))
                self.dlg.tableWidget.setItem(row, 1, QTableWidgetItem(protocol))
                self.dlg.tableWidget.setItem(row, 2, QTableWidgetItem(typename))
                self.dlg.tableWidget.setItem(row, 3, QTableWidgetItem(url))
        else:
            self.dlg.tableWidget.setRowCount(0)  # Clear the table if there are no results
            self.dlg.label_5.show()  # Show the "No results found" label
            self.dlg.tableWidget.hide()  # Hide the table view when there are no results
            self.dlg.label_3.hide()  # Hide the label when there are no results
            self.dlg.pushButton_2.hide()  # Hide the "Load Selected Layers" button when there are no results

        self.update_total_count()  # Update the total count labels after search
        if self.worker is not None:
            self.worker.deleteLater()
            self.worker = None

    def toggle_search_button(self):
        selected_rows = len(self.dlg.tableWidget.selectionModel().selectedRows())

        if selected_rows > 0:
            self.dlg.pushButton_2.setEnabled(True)
            self.dlg.pushButton_2.setText(f"Wählen ({selected_rows})")  # Update button text with the number of selected rows
        else:
            self.dlg.pushButton_2.setEnabled(False)
            self.dlg.pushButton_2.setText("Wählen")  # Reset button text when no rows are selected

    def toggle_remove_button(self):
            selected_rows = len(self.dlg.tableWidget_2.selectionModel().selectedRows())
    
            if selected_rows > 0:
                self.dlg.pushButton_3.setEnabled(True)
                self.dlg.pushButton_3.setText(f"Entfernen ({selected_rows})")  # Update button text with the number of selected rows
            else:
                self.dlg.pushButton_3.setEnabled(False)
                self.dlg.pushButton_3.setText("Entfernen")  # Reset button text when no rows are selected

    def update_total_count(self):
        total_selected_rows = self.dlg.tableWidget_2.rowCount()
        total_available_rows = self.dlg.tableWidget.rowCount()
        if total_selected_rows > 0:
            self.dlg.label_6.setText(f"Gewählte Daten (Gesamtzahl: {total_selected_rows}):") # Update button text with the total number of rows
        else:
            self.dlg.label_6.setText("Gewählte Daten:")

        if total_available_rows > 0:
            self.dlg.label_3.setText(f"Verfügbare Daten (Gesamtzahl: {total_available_rows}):")
        else:
            self.dlg.label_3.setText("Verfügbare Daten:")

    def add_selected_to_Queue(self):
        selected_rows = self.dlg.tableWidget.selectionModel().selectedRows()
        for row in selected_rows:
            title_item = self.dlg.tableWidget.item(row.row(), 0)
            protocol_item = self.dlg.tableWidget.item(row.row(), 1)
            typename_item = self.dlg.tableWidget.item(row.row(), 2)
            url_item = self.dlg.tableWidget.item(row.row(), 3)

            if title_item and protocol_item and typename_item and url_item:
                title = title_item.text()
                protocol = protocol_item.text()
                typename = typename_item.text()
                url = url_item.text()

                # Add the selected layer to the second table
                row_position = self.dlg.tableWidget_2.rowCount()
                self.dlg.tableWidget_2.insertRow(row_position)
                self.dlg.tableWidget_2.setItem(row_position, 0, QTableWidgetItem(title))
                self.dlg.tableWidget_2.setItem(row_position, 1, QTableWidgetItem(protocol))
                self.dlg.tableWidget_2.setItem(row_position, 2, QTableWidgetItem(typename))
                self.dlg.tableWidget_2.setItem(row_position, 3, QTableWidgetItem(url))

                self.dlg.tableWidget.removeRow(row.row())  # Remove the row from the first table
        self.update_total_count()

    def remove_selected_from_Queue(self):
        selected_rows = self.dlg.tableWidget_2.selectionModel().selectedRows()
        for row in selected_rows:
            title_item = self.dlg.tableWidget_2.item(row.row(), 0)
            protocol_item = self.dlg.tableWidget_2.item(row.row(), 1)
            typename_item = self.dlg.tableWidget_2.item(row.row(), 2)
            url_item = self.dlg.tableWidget_2.item(row.row(), 3)

            if title_item and protocol_item and typename_item and url_item:
                title = title_item.text()
                protocol = protocol_item.text()
                typename = typename_item.text()
                url = url_item.text()

                # Add the selected layer back to the first table
                self.dlg.tableWidget.show()  # Show the first table if it was hidden
                self.dlg.label_3.show()  # Show the label if it was hidden
                self.dlg.label_5.hide()  # Hide the "No results found" label if it was shown
                row_position = self.dlg.tableWidget.rowCount()
                self.dlg.tableWidget.insertRow(row_position)
                self.dlg.tableWidget.setItem(row_position, 0, QTableWidgetItem(title))
                self.dlg.tableWidget.setItem(row_position, 1, QTableWidgetItem(protocol))
                self.dlg.tableWidget.setItem(row_position, 2, QTableWidgetItem(typename))
                self.dlg.tableWidget.setItem(row_position, 3, QTableWidgetItem(url))

                self.dlg.tableWidget_2.removeRow(row.row())
        self.update_total_count()

    def load_selected_layers(self):
        rows = self.dlg.tableWidget_2.rowCount()
        crs = self.dlg.mQgsProjectionSelectionWidget.crs().authid()
        layer_position = self.dlg.comboBox_2.currentText()
        index = self.layer.get(layer_position, 0)  # Default to 0 if not found
        if rows == 0:
            raise ValueError("No layers selected to load.")
        else:
            for row in range(rows):
                title_item = self.dlg.tableWidget_2.item(row, 0)
                protocol_item = self.dlg.tableWidget_2.item(row, 1)
                typename_item = self.dlg.tableWidget_2.item(row, 2)
                url_item = self.dlg.tableWidget_2.item(row, 3)

                if title_item and protocol_item and typename_item and url_item:
                    title = title_item.text()
                    protocol = protocol_item.text()
                    typename = typename_item.text()
                    url = url_item.text()

                    # Load the layer based on the protocol
                    if protocol == "WMS":
                        uri = f"crs={crs}&dpiMode=7&featureCount=10&format=image/png&layers={typename}&styles&tilePixelRatio=0&url={url}"
                        layer = QgsRasterLayer(uri, title, "wms")
                    elif protocol == "WFS":
                        uri = f"pagingEnabled='default' preferCoordinatesForWfsT11='false' restrictToRequestBBOX='1' srsname='{crs}' typename='{typename}' url='{url}' version='auto'"
                        layer = QgsVectorLayer(uri, title, "wfs")
                    else:
                        print(f"Unsupported protocol: {protocol}")
                        continue

                    if layer.isValid():
                        self.load_layer_with_position(layer, index)
                        self.layer = self.get_new_layer_position()  # Update the layer positions after loading
                        index = index + 1  # Increment index for the next layer
                    else:
                        print(f"Failed to load layer: {title} from {url}")

    def get_new_layer_position(self):
        ordered_layers = QgsProject.instance().layerTreeRoot().layerOrder()
        layer = {}
        layer["Ganz oben"] = 0
        for index, lyr in enumerate(ordered_layers):
            layer['Unter ' + lyr.name() + ' '] = index+1
        return layer
        
    def load_layer_with_position(self,layer, position):
        QgsProject.instance().addMapLayer(layer, False)  # Add the layer without adding it to the legend
        root = QgsProject.instance().layerTreeRoot()

        if position < 0 or position > len(root.children()):
            raise ValueError("Position is out of bounds.")
        else:
            root.insertLayer(position, layer)  # Insert the layer at the specified position

    def reset_ui(self):
        """Reset the UI elements to their initial state after loading layers or when needed."""
        
        # 1. Clear the search input fields
        self.dlg.lineEdit.clear()
        self.dlg.comboBox.setCurrentIndex(0) # Reset to the first option (e.g., Select State...)

        # 2. Reset the progress bar
        self.dlg.progressBar.setValue(0)
        # self.dlg.progressBar.hide() # Can be hidden until a new search starts
        
        # 3. Clear the currently displayed results
        # If you are using QTableWidget:
        # if hasattr(self.dlg, 'tableWidget'):
        #     self.dlg.tableWidget.setRowCount(0)
        # if hasattr(self.dlg, 'tableWidget_2'):
        #     self.dlg.tableWidget_2.setRowCount(0)

        # 4. Re-enable the Search/Download buttons (in case they were disabled while running)
        self.dlg.pushButton.setEnabled(True)
        self.update_total_count()

    def custom_keyPressEvent(self, event):
        if event.key() in (Qt.Key_Return, Qt.Key_Enter):
            return
        else:
            self.original_keyPressEvent(event)
    
    def run(self):
        """Run method that performs all the real work"""
         # Reset the UI elements before starting a new search

        # Create the dialog with elements (after translation) and keep reference
        # Only create GUI ONCE in callback, so that it will only load when the plugin is started
        if self.first_start == True:
            self.first_start = False
            self.dlg = GeodatabaseDialog()
            self.dlg.tableWidget.setSelectionBehavior(QAbstractItemView.SelectRows)
            self.dlg.tableWidget.setSelectionMode(QAbstractItemView.ExtendedSelection)
            self.dlg.tableWidget.horizontalHeader().setSectionResizeMode(QHeaderView.Stretch)
            self.dlg.tableWidget_2.setSelectionBehavior(QAbstractItemView.SelectRows)
            self.dlg.tableWidget_2.setSelectionMode(QAbstractItemView.ExtendedSelection)
            self.dlg.tableWidget_2.horizontalHeader().setSectionResizeMode(QHeaderView.Stretch)

            self.dlg.tableWidget_2.setDragEnabled(True)           
            self.dlg.tableWidget_2.setAcceptDrops(True)           
            self.dlg.tableWidget_2.viewport().setAcceptDrops(True)
            self.dlg.tableWidget_2.setDragDropOverwriteMode(False)
            self.dlg.tableWidget_2.setDropIndicatorShown(True)
            self.dlg.tableWidget_2.setDragDropMode(QAbstractItemView.InternalMove)
            def custom_dropEvent(event):
                source_row = self.dlg.tableWidget_2.currentRow()
                target_row = self.dlg.tableWidget_2.rowAt(event.pos().y())

                if target_row == -1:
                    target_row = self.dlg.tableWidget_2.rowCount()

                if source_row == target_row or source_row == -1:
                    event.ignore()
                    return

                row_data = []
                for col in range(self.dlg.tableWidget_2.columnCount()):
                    item = self.dlg.tableWidget_2.takeItem(source_row, col)
                    row_data.append(item.text() if item else "")

                self.dlg.tableWidget_2.insertRow(target_row)

                for col, data in enumerate(row_data):
                    self.dlg.tableWidget_2.setItem(target_row, col, QTableWidgetItem(data))

                if target_row < source_row:
                    self.dlg.tableWidget_2.removeRow(source_row+1)
                else:
                    self.dlg.tableWidget_2.removeRow(source_row)

                event.accept()
            self.dlg.tableWidget_2.dropEvent = custom_dropEvent

            
            self.dlg.tableWidget.setColumnCount(4)  # Set the number of columns to 4
            self.dlg.tableWidget_2.setColumnCount(4)  # Set the number of columns to 4
            self.dlg.tableWidget.setHorizontalHeaderLabels(["Title", "Protocol", "Type Name", "URL"])
            self.dlg.tableWidget_2.setHorizontalHeaderLabels(["Title", "Protocol", "Type Name", "URL"])
            self.dlg.label_5.hide()
            self.dlg.tableWidget.hide()  # Hide the table view initially
            self.dlg.label_3.hide()  # Hide the label initially
            self.dlg.pushButton_2.hide()
            self.dlg.pushButton_2.setEnabled(False)
            self.dlg.pushButton_3.setEnabled(False)
            self.dlg.tableWidget.itemSelectionChanged.connect(self.toggle_search_button)
            self.dlg.tableWidget_2.itemSelectionChanged.connect(self.toggle_remove_button)
            self.create_quick_search_ui()  # Create the quick search UI elements

            self.dlg.lineEdit.returnPressed.connect(self.findServices)  # Connect the returnPressed signal to findServices
            self.original_keyPressEvent = self.dlg.keyPressEvent  # Store the original keyPressEvent method

        # #reset the UI elements before starting a new search
        self.reset_ui()

        self.dlg.keyPressEvent = self.custom_keyPressEvent 

        #Fetch the current crs
        self.current_crs = QgsProject.instance().crs()
        self.dlg.mQgsProjectionSelectionWidget.setCrs(self.current_crs)
        
        self.dlg.comboBox.clear()
        self.dlg.comboBox.addItems(self.states)

        self.dlg.comboBox_2.clear()
        self.layer = self.get_new_layer_position()
        self.dlg.comboBox_2.addItems(self.layer.keys())

        
        self.dlg.pushButton.clicked.connect(self.findServices)
        self.dlg.progressBar.setValue(0)# Initialize progress bar to 0
        self.dlg.pushButton_2.clicked.connect(self.add_selected_to_Queue)
        self.dlg.pushButton_3.clicked.connect(self.remove_selected_from_Queue)

        # show the dialog
        self.dlg.show()
        # Run the dialog event loop
        result = self.dlg.exec_()
        # See if OK was pressed
        if result:
            # Do something useful here - delete the line containing pass and
            # substitute with your code.
            self.load_selected_layers()

